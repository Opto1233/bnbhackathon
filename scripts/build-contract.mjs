import { readFileSync, writeFileSync } from 'node:fs'
import solc from 'solc'

const filename = 'contracts/RelicMarket.sol'
const input = {
  language: 'Solidity',
  sources: { [filename]: { content: readFileSync(filename, 'utf8') } },
  settings: {
    evmVersion: 'paris',
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode'] } },
  },
}
const output = JSON.parse(solc.compile(JSON.stringify(input), {
  import: path => {
    try { return { contents: readFileSync('node_modules/' + path, 'utf8') } }
    catch { return { error: 'Missing dependency: ' + path } }
  },
}))
const errors = output.errors?.filter(error => error.severity === 'error') ?? []
if (errors.length) throw new Error(errors.map(error => error.formattedMessage).join('\n'))
const { RelicMarket, TestRelic, VaultRelic } = output.contracts[filename]
writeFileSync('src/lib/relic-contracts.ts', [
  '// Generated by npm run build:contracts.',
  'export const marketAbi = ' + JSON.stringify(RelicMarket.abi, null, 2) + ' as const',
  'export const coinAbi = ' + JSON.stringify(TestRelic.abi, null, 2) + ' as const',
  'export const relicAbi = ' + JSON.stringify(VaultRelic.abi, null, 2) + ' as const',
  'export const marketRuntime = "0x' + RelicMarket.evm.deployedBytecode.object + '" as const',
  'export const marketImmutableRanges = ' + JSON.stringify(Object.values(RelicMarket.evm.deployedBytecode.immutableReferences).flat()) + ' as const',
  'export const marketBytecode = "0x' + RelicMarket.evm.bytecode.object + '" as const',
  '',
].join('\n'))
